import { readFile, writeFile, mkdtemp, mkdir, rm, lstat, readdir, chmod } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import os from 'node:os';

// An unreleased package is still a distribution of source and must not pick up
// local credentials, symlink targets or untracked files from a developer's tree.
const sourceEntries = ['.github', '.gitignore', 'AGENTS.md', 'README.md', 'README.en.md', 'README_EN.md',
    'LICENSE', 'NOTICE', 'build.sh', 'deploy.sh', 'package.json', 'package-lock.json',
    'client', 'server', 'scripts', 'deployment', 'docs', 'tests', 'licenses'];
const forbiddenParts = /^(?:\.git|\.env(?:\..*)?|\.npmrc|\.netrc|node_modules|test-results|playwright-report)$/i;
const credentialFile = /(?:\.(?:pem|key|p12|pfx|jks|keystore)|(?:^|\/)(?:id_rsa|id_ed25519|credentials(?:\.json)?))$/i;
const secretRules = [
    ['private-key', /-----BEGIN (?:[A-Z0-9]+ )?PRIVATE KEY-----/],
    ['github-token', /\b(?:gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{40,})\b/],
    ['aws-access-key', /\b(?:AKIA|ASIA)[A-Z0-9]{16}\b/],
    ['openai-project-key', /\bsk-proj-[A-Za-z0-9_-]{24,}\b/]
];
export function forbiddenCandidatePath(name) {
    return name.split('/').some(part => forbiddenParts.test(part)) || credentialFile.test(name);
}
export function candidateSecretRule(bytes) {
    const text = bytes.toString('utf8');
    return secretRules.find(([, pattern]) => pattern.test(text))?.[0] || null;
}
async function plainFile(root, relative) {
    for (const part of relative.split('/')) {
        root = path.join(root, part);
        if ((await lstat(root)).isSymbolicLink()) throw Error('Symlink input rejected: ' + relative);
    }
    if (!(await lstat(root)).isFile()) throw Error('Non-file input rejected: ' + relative);
    return root;
}
async function distFiles(root, relative = 'dist') {
    const out = [];
    for (const entry of await readdir(path.join(root, relative), { withFileTypes: true })) {
        const name = relative + '/' + entry.name;
        if (entry.isSymbolicLink()) throw Error('Symlink input rejected: ' + name);
        if (entry.isDirectory()) out.push(...await distFiles(root, name));
        else if (entry.isFile()) out.push(name);
        else throw Error('Non-file input rejected: ' + name);
    }
    return out.sort();
}
export async function packageCandidate({ root = path.resolve(import.meta.dirname, '..'), output, verifyBuild = true } = {}) {
    root = path.resolve(root); output ||= path.join(root, 'test-results', 'candidate');
    const git = args => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
    const commit = git(['rev-parse', 'HEAD']).trim();
    if (!/^[a-f0-9]{40}$/.test(commit)) throw Error('Missing verified source commit');
    // Do not stamp an archive with a HEAD that does not represent its source.
    if (git(['status', '--porcelain', '--untracked-files=no']).trim()) throw Error('Candidate requires clean tracked source at HEAD');
    const tree = git(['ls-tree', '-r', '-z', 'HEAD', '--', ...sourceEntries]).split('\0').filter(Boolean);
    const modes = new Map(tree.map(entry => [entry.slice(entry.indexOf('\t') + 1), entry.split(' ')[0]]));
    const tracked = [...modes.keys()].sort();
    if (!tracked.length) throw Error('Missing tracked candidate sources');
    const client = new Set(tracked.filter(name => name.startsWith('client/')).map(name => 'dist/' + name.slice(7)));
    for (const extra of ['LICENSE', 'NOTICE', 'THIRD_PARTY_LICENSES.txt', 'build.json']) client.add('dist/' + extra);
    // This command proves generated bytes correspond to the clean source tree,
    // and already checks all shell/icon references. It never deploys anything.
    if (verifyBuild) execFileSync(process.execPath, ['scripts/check-build.mjs'], { cwd: root, stdio: ['ignore', 'pipe', 'pipe'] });
    const built = await distFiles(root);
    if (built.some(name => !client.has(name))) throw Error('Untracked or unexpected asset in dist');
    if ([...client].some(name => !built.includes(name))) throw Error('Build missing expected asset');
    const build = JSON.parse(await readFile(path.join(root, 'dist/build.json'), 'utf8'));
    const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
    if (!/^[a-f0-9]{16}$/.test(build.revision) || build.version !== pkg.version) throw Error('Missing or mismatched build identity');
    const inputs = [...tracked, ...built];
    const temp = await mkdtemp(path.join(os.tmpdir(), 'zeydrop-pack-'));
    const stage = path.join(temp, 'zeydrop-candidate');
    let totalBytes = 0; const files = [];
    try {
        await mkdir(stage);
        for (const name of inputs) {
            if (forbiddenCandidatePath(name)) throw Error('Credential or forbidden path rejected: ' + name);
            const source = await plainFile(root, name);
            const size = (await lstat(source)).size;
            if (size > 8 * 1024 * 1024 || (totalBytes += size) > 64 * 1024 * 1024) throw Error('Candidate input budget exceeded');
            const bytes = await readFile(source);
            const rule = candidateSecretRule(bytes);
            if (rule) throw Error('Candidate secret scan rejected ' + name + ' (rule: ' + rule + ')');
            const destination = path.join(stage, name); await mkdir(path.dirname(destination), { recursive: true });
            await writeFile(destination, bytes);
            // Normalize archive permissions to the tracked executable bit.
            const mode = name.startsWith('dist/') ? '100644' : modes.get(name);
            await chmod(destination, mode === '100755' ? 0o755 : 0o644);
            files.push({ path: name, origin: name.startsWith('dist/') ? 'verified-build' : 'HEAD', bytes: size, mode: mode === '100755' ? '755' : '644', sha256: createHash('sha256').update(bytes).digest('hex') });
        }
        // Detect source modifications while the snapshot was being prepared.
        if (git(['rev-parse', 'HEAD']).trim() !== commit || git(['status', '--porcelain', '--untracked-files=no']).trim()) throw Error('Source changed while packaging');
        const normalizeDirectories = async dir => {
            await chmod(dir, 0o755);
            for (const item of await readdir(dir, { withFileTypes: true })) if (item.isDirectory()) await normalizeDirectories(path.join(dir, item.name));
        };
        await normalizeDirectories(stage);
        const raw = path.join(temp, 'archive.tar');
        execFileSync('tar', ['--sort=name', '--mtime=@0', '--owner=0', '--group=0', '--numeric-owner', '--format=gnu', '-cf', raw, '-C', temp, 'zeydrop-candidate']);
        const archive = gzipSync(await readFile(raw), { level: 9, mtime: 0 });
        const sha256 = createHash('sha256').update(archive).digest('hex');
        const filename = 'zeydrop-candidate.tar.gz';
        for (const required of ['dist/index.html', 'server/index.js', 'deploy.sh', 'package-lock.json', 'LICENSE'])
            if (!inputs.includes(required)) throw Error('Archive missing ' + required);
        await mkdir(output, { recursive: true });
        await writeFile(path.join(output, filename), archive);
        await writeFile(path.join(output, filename + '.sha256'), sha256 + '  ' + filename + '\n');
        const manifest = {
            schema: 2, product: 'Zeydrop', status: 'unreleased-developer-test-candidate', commit,
            revision: build.revision, version: build.version, archive: filename, sha256, bytes: archive.length,
            containsNodeModules: false, sourceSnapshot: 'clean-HEAD-tracked-files', files,
            excluded: ['untracked source files', 'node_modules', '.env*', '.git', '.npmrc', '.netrc', 'test-results', 'credential files', 'symlinks'],
            secretScan: { status: 'passed-bounded-pattern-scan', rules: secretRules.map(([id]) => id), guarantee: 'Pattern scan is not proof that all possible credentials are absent; manual review remains required.' },
            notice: 'NOT a stable release or proof of real ISP NAT reachability. Deploy only in a separate test environment.'
        };
        await writeFile(path.join(output, 'candidate-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
        return manifest;
    } finally { await rm(temp, { recursive: true, force: true }); }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const result = await packageCandidate();
    console.log('PASS reproducible development candidate', result.commit.slice(0, 12), result.revision, result.sha256);
}
